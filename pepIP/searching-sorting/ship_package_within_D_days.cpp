double tick() {
    static clock_t oldt, newt = clock();
    double diff = 1.0 * (newt - oldt) / CLOCKS_PER_SEC;
    oldt = newt;
    return diff;
}

int reqday(int mid, vector<int>& v) {
    int cnt = 1, sum = 0;
    int i = -1;
    while (i < v.size()) {
        i++;
        if (i == v.size()) break;
        sum += v[i];
        if (sum > mid) {
            cnt++;
            i = i-1;
            sum = 0;
        }
    }
    return cnt;
}

